import { ChangeDetectionStrategy, Component, computed, inject, signal } from '@angular/core';
import { MapViewService } from '../map-view/map-view.service';
import { LocationDTO } from '../../../core/DTOs/location/location-dto';
import { locationStatusTone } from '../../../core/utils/location-util';
import { LocationService } from '../../../core/services/api-services/location.service';

/** Search box + quick place chips. Picking a place selects it on the map and focuses it. */
@Component({
  selector: 'app-buildings-search',
  templateUrl: './buildings-search.component.html',
  changeDetection: ChangeDetectionStrategy.OnPush,
  host: { '(document:click)': 'onDocumentClick($event)' },
})
export class BuildingsSearchComponent {
  private readonly selection = inject(MapViewService);
  private readonly buildings = inject(LocationService).buildings;

  // protected
  protected readonly locationStatusTone = locationStatusTone;
  /** null when nothing, or a custom pin, is selected (highlights the matching quick chip) */
  protected readonly selectedLocationId = this.selection.selectedLocationId;

  // signals
  /** what the input shows: updates on every key */
  protected readonly searchQuery = signal('');
  protected readonly searchOpen = signal(false);

  // computed
  /** the first buildings the api returns (the ids are generated by the server, so they can't be hard-coded) */
  protected readonly quickPlaces = computed(() => this.buildings());
  protected readonly searchResults = computed(() => {
    const query = this.searchQuery().trim().toLowerCase();
    if (!query) return [];

    return this.buildings().filter((b) => b.title.toLowerCase().includes(query));
  });

  // methods
  protected onSearchInput(value: string): void {
    this.searchQuery.set(value);
    this.searchOpen.set(value.trim().length > 0);
  }

  /** the one place where a pick (chip or search result) becomes a selection + focus */
  protected choose(building: LocationDTO): void {
    this.selection.selectAndFocusLocation(building.id);
  }

  protected pickSearchResult(building: LocationDTO): void {
    this.choose(building);
    this.searchQuery.set(building.title);
    this.searchOpen.set(false);
  }

  protected clearSearch(): void {
    this.searchQuery.set('');
    this.searchOpen.set(false);
  }

  protected onDocumentClick(event: MouseEvent): void {
    if (!(event.target as HTMLElement).closest('[data-search]')) this.searchOpen.set(false);
  }
}
